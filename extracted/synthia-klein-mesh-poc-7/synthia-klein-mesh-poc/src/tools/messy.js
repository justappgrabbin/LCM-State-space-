// messy.js
// Klein 1976: MESSY (Meta-symbolic Simulation System) — agents with feature
// vectors transformed by scripted rules over discrete ticks. This mirrors
// your organ_base.py cycle: State -> Relation -> Tension -> Resolution ->
// Recursion. Implemented generically so any agent set + rule set can run.

import { ToolBase } from './ToolBase.js';

export class Messy extends ToolBase {
  constructor(mesh) {
    super(mesh, 'Messy', 'sim.messy');
  }

  /**
   * input = {
   *   agents: [{ id, features: {k:v,...} }],
   *   rules: [{ when: (agent, world) => bool, apply: (agent, world) => agent }],
   *   ticks: number
   * }
   */
  run(input) {
    const { agents, rules, ticks = 5 } = input;
    let state = agents.map((a) => ({ id: a.id, features: { ...a.features } }));
    const history = [{ tick: 0, state: structuredClone(state) }];

    for (let t = 1; t <= ticks; t++) {
      state = state.map((agent) => {
        const world = { tick: t, agents: state };
        const rule = rules.find((r) => r.when(agent, world));
        if (!rule) return agent; // STATE: no applicable rule, stays put
        const next = rule.apply(agent, world); // RELATION -> TENSION -> RESOLUTION
        return next; // RECURSION: feeds into next tick
      });
      history.push({ tick: t, state: structuredClone(state) });
    }

    return { ok: true, ticks, finalState: state, history };
  }

  /**
   * codegen(): emits a STANDALONE, runnable HTML5 canvas world/game from
   * the SAME agent+rule structure used for simulation. This is the
   * "messy should do everything — worlds, images, games" capability:
   * Messy's state-transition engine becomes a game loop, and agents
   * become drawn entities. No AI model involved — it's a direct
   * transliteration of the simulation rules into a render loop.
   *
   * input = {
   *   title?: string,
   *   agents: [{ id, features: { x, y, color?, radius? } }],
   *   ruleDescriptions: string[]  // human-readable, embedded as comments
   * }
   */
  codegen(input) {
    const { title = 'Messy World', agents = [], ruleDescriptions = [] } = input;
    const initialAgents = JSON.stringify(agents.map((a) => ({ id: a.id, ...a.features })));
    const comments = ruleDescriptions.map((r) => `      // RULE: ${r}`).join('\n');

    return `<!doctype html>
<html><head><meta charset="utf-8"><title>${title}</title></head>
<body style="margin:0;background:#0a0a0a">
<canvas id="c" width="640" height="480"></canvas>
<script>
// Generated by Messy.codegen() — meta-symbolic simulation as a game loop.
// State -> Relation -> Tension -> Resolution -> Recursion, drawn each frame.
const ctx = document.getElementById('c').getContext('2d');
let agents = ${initialAgents};

function tick() {
${comments || '      // (no rules described — agents are static)'}
  agents = agents.map(a => {
    // TENSION/RESOLUTION: simple drift + boundary bounce as a default rule.
    // Replace this with real rules translated from your Messy ruleset.
    let { x = 50, y = 50, vx = 1, vy = 1, radius = 8, color = '#10d474' } = a;
    x += vx; y += vy;
    if (x < radius || x > 640 - radius) vx *= -1;
    if (y < radius || y > 480 - radius) vy *= -1;
    return { ...a, x, y, vx, vy, radius, color };
  });
}

function draw() {
  ctx.fillStyle = '#0a0a0a';
  ctx.fillRect(0, 0, 640, 480);
  for (const a of agents) {
    ctx.beginPath();
    ctx.fillStyle = a.color || '#10d474';
    ctx.arc(a.x ?? 50, a.y ?? 50, a.radius ?? 8, 0, Math.PI * 2);
    ctx.fill();
  }
}

function loop() {
  tick();
  draw();
  requestAnimationFrame(loop);
}
loop();
</script>
</body></html>`;
  }
}
