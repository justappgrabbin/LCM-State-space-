// novelWriter.js
// Klein et al. 1973: "Automatic Novel Writing" — generative narrative using
// script-like world-knowledge rules. This is a Propp-function story grammar:
// a fixed sequence of narrative functions, each filled from a slot table,
// with branching driven by a seeded PRNG so output is reproducible.

import { ToolBase } from './ToolBase.js';

const FUNCTIONS = [
  'LACK',        // something is missing
  'DEPARTURE',   // hero leaves
  'TEST',        // hero is tested
  'STRUGGLE',    // hero confronts the antagonist
  'VICTORY',     // antagonist is defeated
  'RETURN',      // hero returns
  'RECOGNITION', // hero is recognized/transformed
];

function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function pick(rng, arr) {
  return arr[Math.floor(rng() * arr.length)];
}

const SLOTS = {
  hero: ['the architect', 'a wandering signal', 'the ninth gate', 'a fractured channel'],
  lack: ['coherence', 'a missing field', 'a broken link to the source', 'silence where a tone should be'],
  antagonist: ['entropy', 'a false lock', 'the dual-runtime conflict', 'a regression to generic form'],
  boon: ['a recovered rule table', 'a re-synced lattice address', 'a working mesh', 'a closed loop'],
};

export class NovelWriter extends ToolBase {
  constructor(mesh) {
    super(mesh, 'NovelWriter', 'narrative.novelwriter');
  }

  /** input = { seed?: number } */
  run(input = {}) {
    const seed = input.seed ?? Date.now() % 100000;
    const rng = mulberry32(seed);
    const hero = pick(rng, SLOTS.hero);
    const lack = pick(rng, SLOTS.lack);
    const antagonist = pick(rng, SLOTS.antagonist);
    const boon = pick(rng, SLOTS.boon);

    const beats = FUNCTIONS.map((fn) => {
      switch (fn) {
        case 'LACK': return `${hero} is missing ${lack}.`;
        case 'DEPARTURE': return `${hero} leaves stable ground to find it.`;
        case 'TEST': return `${hero} is tested by ${antagonist}.`;
        case 'STRUGGLE': return `${hero} confronts ${antagonist} directly.`;
        case 'VICTORY': return `${antagonist} is resolved, not destroyed.`;
        case 'RETURN': return `${hero} returns carrying ${boon}.`;
        case 'RECOGNITION': return `${hero} is recognized as changed.`;
        default: return '';
      }
    });

    return { ok: true, seed, hero, lack, antagonist, boon, beats };
  }

  /** codegen(): emits a standalone JS module that regenerates this exact story (same seed = same output, since mulberry32 is deterministic). */
  codegen(input = {}) {
    const seed = input.seed ?? 42;
    return `// Generated by NovelWriter.codegen() — deterministic, seed=${seed}.
// Run with: node thisFile.js
${mulberry32.toString()}
${pick.toString()}
const SLOTS = ${JSON.stringify(SLOTS, null, 2)};
const FUNCTIONS = ${JSON.stringify(FUNCTIONS)};

function generateStory(seed) {
  const rng = mulberry32(seed);
  const hero = pick(rng, SLOTS.hero);
  const lack = pick(rng, SLOTS.lack);
  const antagonist = pick(rng, SLOTS.antagonist);
  const boon = pick(rng, SLOTS.boon);
  return FUNCTIONS.map(fn => {
    switch (fn) {
      case 'LACK': return \`\${hero} is missing \${lack}.\`;
      case 'DEPARTURE': return \`\${hero} leaves stable ground to find it.\`;
      case 'TEST': return \`\${hero} is tested by \${antagonist}.\`;
      case 'STRUGGLE': return \`\${hero} confronts \${antagonist} directly.\`;
      case 'VICTORY': return \`\${antagonist} is resolved, not destroyed.\`;
      case 'RETURN': return \`\${hero} returns carrying \${boon}.\`;
      case 'RECOGNITION': return \`\${hero} is recognized as changed.\`;
      default: return '';
    }
  });
}

console.log(generateStory(${seed}).join('\\n'));
`;
  }
}
